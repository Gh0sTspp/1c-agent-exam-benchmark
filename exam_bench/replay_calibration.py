"""Calibration by replay: a new grader judged on the observations of an earlier accepted full calibration.

A full calibration observes 74 configurations in 1C and then checks the verdicts. When only the
verdict logic changed since, the observations stay valid and 1C is needed once, not 74 times:

1. code check — the configurations, bindings and observer code that produce the observations are
   generated by the source calibration's commit and by the current code; they must be identical
   (random UUIDs aside);
2. platform check — one positive variant runs in 1C on this machine and must reproduce the stored
   observations exactly;
3. replay — every stored run is graded again by the current grader with 1C replaced by its stored
   observations; acceptance criteria are those of the full calibration.

Any difference means the full calibration must run instead.
"""
import contextlib
import copy
import json
import subprocess
import sys
import tempfile
from pathlib import Path

from .calibration import generate
from .common import digest, grading_fingerprint, runtime_fingerprint, tree_manifest, write_json
from . import grader

ROOT = Path(__file__).resolve().parents[1]

# Runs with the exam_bench package of the given code root, so the same script fingerprints an old
# commit and the current code. It uses only interfaces present in both.
FINGERPRINT = r'''
import hashlib, json, re, sys, tempfile
from pathlib import Path
code_root, starter, items = sys.argv[1], Path(sys.argv[2]), json.loads(sys.argv[3])
sys.path.insert(0, code_root)
from exam_bench.calibration import generate
from exam_bench import grader, ou, pr, forms, interface, queries
from exam_bench.submission import strip_extras, canonical_ledger
UUID = re.compile(rb'[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}')
h = lambda b: hashlib.sha256(UUID.sub(b'<uuid>', b)).hexdigest()
out = {}
for variant, mutant in items:
    with tempfile.TemporaryDirectory() as td:
        target = Path(td) / 'src'
        binding = generate(starter, target, variant, mutant)
        files = {p.relative_to(target).as_posix(): h(p.read_bytes()) for p in sorted(target.rglob('*')) if p.is_file()}
        b, _ = strip_extras(binding); b, _ = canonical_ledger(target, b)
        observers = {name: h(grader.code(b, case).encode()) for name, case in grader.CASES.items()}
        for key, module in (('ou', ou), ('pr', pr), ('forms', forms), ('interface', interface)):
            if key in b:
                for name, case in module.CASES.items():
                    client = module.client_code(b) if hasattr(module, 'client_code') else None
                    observers[name] = h((module.code(b, case, grader.HELPERS) + (client or '')).encode())
        observers['query_texts'] = h(queries.code(target).encode())
        out[mutant or variant] = {'files': files, 'binding': h(json.dumps(binding, sort_keys=True).encode()), 'observers': observers}
print(json.dumps(out, sort_keys=True))
'''


def items(summary):
    return [(p['variant'], None) for p in summary['positives'] if p['repetition'] == 1] + \
           [('one', n['mutation']) for n in summary['negatives']]


def observation_inputs(code_root, starter_source, summary):
    result = subprocess.run([sys.executable, '-I', '-c', FINGERPRINT, str(code_root), str(starter_source), json.dumps(items(summary))],
                            capture_output=True, text=True, check=True)
    return json.loads(result.stdout)


def source_commit(summary):
    """The commit whose grading files are exactly those the source calibration recorded."""
    import hashlib
    show = lambda commit, name: subprocess.run(['git', 'show', f'{commit}:exam_bench/{name}'], cwd=ROOT, capture_output=True).stdout
    # All local refs: the source may predate the current history (e.g. kept only under a local tag).
    log = subprocess.run(['git', 'log', '--all', '--format=%H', '--', 'exam_bench'], cwd=ROOT, capture_output=True, text=True, check=True)
    for commit in log.stdout.split():
        if all(hashlib.sha256(show(commit, name)).hexdigest() == value for name, value in summary['implementation_files'].items()):
            return commit
    return None


def code_unchanged(summary, starter_source):
    """Whether the current code generates exactly what the source calibration observed."""
    commit = source_commit(summary)
    if commit is None:
        return None, 'source_commit_not_found'
    with tempfile.TemporaryDirectory(prefix='replay-code-') as td:
        tree = Path(td) / 'code'
        subprocess.run(['git', 'worktree', 'add', '--detach', str(tree), commit], cwd=ROOT, capture_output=True, check=True)
        try:
            old = observation_inputs(tree, starter_source, summary)
        finally:
            subprocess.run(['git', 'worktree', 'remove', '--force', str(tree)], cwd=ROOT, capture_output=True)
    new = observation_inputs(ROOT, starter_source, summary)
    return commit, sorted(k for k in set(old) | set(new) if old.get(k) != new.get(k))


@contextlib.contextmanager
def stored_platform(observations):
    """1C replaced by the stored observations of one run; everything after observation is the current grader."""
    current = {}

    @contextlib.contextmanager
    def workspace(root):
        current['case'] = Path(root).name
        yield Path(root)

    class Replayed:
        def __init__(self, binary, path, timeout): pass
        def restore(self, ib, starter): pass
        def load(self, ib, source): pass
        def command(self, args, label, confined=None):
            Path(args[-1]).write_text(json.dumps(observations[current['case']], ensure_ascii=False), encoding='utf-8')

    saved = grader.case_workspace, grader.OneC, grader.inject
    grader.case_workspace, grader.OneC, grader.inject = workspace, Replayed, lambda source, target, *a, **k: target
    try:
        yield
    finally:
        grader.case_workspace, grader.OneC, grader.inject = saved


def replay_run(source_dir, grade_ref, folder, evidence):
    stored = json.loads((source_dir / grade_ref).read_text(encoding='utf-8'))
    observations = {**stored['observations'], **{k: {'error': v.get('message', 'stored error')} for k, v in stored['errors'].items()}}
    binding = json.loads((source_dir / folder / 'binding.json').read_text(encoding='utf-8'))
    with stored_platform(observations):
        return grader.grade(source_dir / folder / 'src', binding, None, None, evidence, list(observations)), stored


def replay_calibrate(source_dir, starter_source, starter_dt, binary, root):
    from .preflight import verify_calibration
    from .runtime import machine_identity, require_execution_mode, platform_binary
    require_execution_mode()
    if str(Path(binary).resolve()) != platform_binary():
        raise ValueError('Calibration binary must match the machine settings')
    source_dir, root = Path(source_dir).resolve(), Path(root).resolve()
    summary = json.loads((source_dir / 'summary.json').read_text(encoding='utf-8'))
    if not summary.get('accepted') or summary.get('mode') in ('quick', 'replay') or not summary.get('negatives'):
        raise ValueError('The source must be an accepted full calibration')
    root.mkdir(parents=True, exist_ok=False)
    implementation = grading_fingerprint()
    result = {'schema_version': 1, 'fingerprint_version': 2, 'runtime_implementation_files': runtime_fingerprint(), 'mode': 'replay', 'profile_id': grader.PROFILE['id'], 'accepted': False,
              'grader_sha256': digest(Path(__file__).parent / 'grader.py'), 'calibration_generator_sha256': digest(Path(__file__).parent / 'calibration.py'),
              'source_summary_sha256': digest(source_dir / 'summary.json'), 'positives': [], 'negatives': [],
              'implementation_files': implementation, 'readonly_sources_verified': False, 'machine': machine_identity()}

    write_json(root / 'progress.json', {'phase': 'code'})
    commit, different = code_unchanged(summary, starter_source)
    result.update(source_commit=commit, observation_inputs_differ=different)
    if commit is None or different:
        result['reason'] = 'observation_code_changed' if commit else different
        write_json(root / 'summary.json', result)
        return result

    write_json(root / 'progress.json', {'phase': 'platform'})
    positive = next(p for p in summary['positives'] if p['variant'] == 'one' and p['repetition'] == 1)
    stored_one = json.loads((source_dir / positive['grade_ref']).read_text(encoding='utf-8'))['observations']
    check = root / 'platform-check'
    check.mkdir()
    binding = generate(starter_source, check / 'src', 'one')
    for path in (check / 'src').rglob('*'):
        if path.is_file():
            path.chmod(0o444)
    live = grader.grade(check / 'src', binding, starter_dt, binary, check / 'grade')
    platform_differs = sorted(c for c in set(stored_one) | set(live['observations']) if stored_one.get(c) != live['observations'].get(c))
    result.update(platform_check={'status': live['status'], 'errors': bool(live['errors']), 'different_cases': platform_differs})
    if platform_differs or live['errors'] or live['status'] != 'partial_pass':
        result['reason'] = 'platform_observations_differ'
        write_json(root / 'summary.json', result)
        return result

    write_json(root / 'progress.json', {'phase': 'replay'})
    previous, baseline = {}, None
    for p in summary['positives']:
        ref = f"{p['variant']}/grade-{p['repetition']}/grade.json"
        g, stored = replay_run(source_dir, p['grade_ref'], p['variant'], root / ref.rsplit('/', 1)[0])
        same = p['variant'] not in previous or previous[p['variant']] == g['observations']
        previous[p['variant']] = g['observations']
        result['positives'].append({'variant': p['variant'], 'repetition': p['repetition'], 'grade_ref': ref,
                                    'passed': g['status'] == 'partial_pass', 'same_observations_as_prior': same})
        if p['variant'] == 'one' and p['repetition'] == 1:
            baseline = (g, json.loads((source_dir / 'one/binding.json').read_text(encoding='utf-8')))
    for n in summary['negatives']:
        ref = f"{n['mutation']}/grade/grade.json"
        g, stored = replay_run(source_dir, n['grade_ref'], n['mutation'], root / n['mutation'] / 'grade')
        verdict = next(r['verdict'] for r in g['rules'] if r['id'] == n['rule'])
        cases = [c for c in list(stored['observations']) + list(stored['errors'])]
        result['negatives'].append({'mutation': n['mutation'], 'rule': n['rule'], 'grade_ref': ref, 'target_verdict': verdict,
                                    'runtime_observations_available': all(c in g['observations'] for c in cases),
                                    'syntax_or_adapter_errors': bool(g['errors'])})
    g, b = baseline
    leaked = copy.deepcopy(g['observations'])
    leaked['oversell']['after'].append(copy.deepcopy(leaked['average']['after'][-1]))
    leaked['oversell']['all_after']['injected_leak'] = ['changed']
    leak_check = next(r for r in grader.compare(leaked, b) if r['id'] == 'BU10')['verdict'] == 'fail'
    from .calibration_query import run as calibrate_query
    query_calibration = calibrate_query(starter_source, starter_dt, binary, root / 'query-parameter')
    from .calibration_periodicity import run as calibrate_periodicity
    periodicity_calibration = calibrate_periodicity(starter_source, starter_dt, binary, root / 'periodicity')
    from .calibration_characteristics import run as calibrate_characteristics
    characteristics_calibration = calibrate_characteristics(starter_source, starter_dt, binary, root / 'characteristics')
    if implementation != grading_fingerprint():
        raise ValueError('Grading implementation changed during calibration')
    result.update(unposted_movement_leak_oracle_check=leak_check, readonly_sources_verified=True,
                  query_parameter_calibration=query_calibration,
                  periodicity_calibration=periodicity_calibration,
                  characteristics_calibration=characteristics_calibration,
                  accepted=leak_check and query_calibration['passed'] and periodicity_calibration['passed'] and characteristics_calibration['passed'] and all(p['passed'] and p['same_observations_as_prior'] for p in result['positives']) and
                  all(n['target_verdict'] == 'fail' and n['runtime_observations_available'] and not n['syntax_or_adapter_errors']
                      for n in result['negatives']))
    if not result['accepted']:
        result['reason'] = 'replayed_verdicts_failed'
    write_json(root / 'summary.json', result)
    if result['accepted']:
        verify_calibration(result)
    return result
